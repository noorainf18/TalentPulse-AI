"""
Node 7 — Email (Rejection Only)
Sends a feedback-rich rejection email to candidates whose score is below
the rejection threshold (< 50).

What changed from the original:
  - Removed _build_screening_email() and all "score > 70 → invite" logic.
    Screening invitations are now handled exclusively by the voice pipeline:
    schedule_voice_screen (Celery task) sends the voice interview invite
    after the LiveKit room and questions are prepared.

  - email_node is now called ONLY for rejections (score < 50).
    graph.py's route_after_voice() conditional edge ensures email_node
    is only reached when score < 50.

  - Borderline candidates (50–59) never reach this node; graph routes
    them straight to END for human review (HITL — on hold).

Post-voice "next round" emails:
  After the voice interview completes, tasks.analyze_transcript() calls
  send_next_round_email() (defined in this module and importable) if the
  candidate's final_merged_score meets VOICE_PASS_THRESHOLD.
"""

import logging
from django.conf import settings
import resend
from talentplus_ai.agent.state import AgentState

logger = logging.getLogger(__name__)


# ---------------------------------------------------------------------------
# Rejection email (called by email_node inside the LangGraph pipeline)
# ---------------------------------------------------------------------------

def _build_rejection_email(state: AgentState) -> tuple[str, str]:
    """Returns (subject, html_body) for a feedback-rich rejection."""
    name = state.get("name", "there")
    score = state.get("score", 0)
    gap_analysis = state.get("gap_analysis", {})
    critical_gaps = gap_analysis.get("critical_gaps", [])
    best_role = gap_analysis.get("best_match_role", "the role")
    github_evidence = state.get("github_evidence", {})

    gaps_html = ""
    if critical_gaps:
        items = "".join(f"<li>{g}</li>" for g in critical_gaps[:4])
        gaps_html = f"""
        <p>The key skill gaps we identified for <strong>{best_role}</strong>:</p>
        <ul>{items}</ul>
        <p>Building experience in these areas would significantly strengthen your profile
        for future applications.</p>
        """

    has_original = github_evidence.get("has_original_work", False) if github_evidence else False
    github_tip = ""
    if not has_original and not github_evidence.get("skipped"):
        github_tip = """
        <p><strong>One tip:</strong> We noticed your GitHub repos are primarily forks.
        Publishing original projects — even small ones — makes a significant difference
        in evidence-based evaluations.</p>
        """

    subject = f"Your application to TalentPlus AI — {name}"

    html_body = f"""
    <div style="font-family: Arial, sans-serif; max-width: 600px; margin: 0 auto;">
      <h2 style="color: #1a1a2e;">Thank you for applying, {name}</h2>

      <p>We've carefully reviewed your profile using our AI evaluation system.
      After analysis, we won't be moving forward with your application at this time
      (evaluation score: {score}/100).</p>

      {gaps_html}
      {github_tip}

      <p>We genuinely encourage you to apply again in the future as you develop
      these skills — your profile showed real potential in other areas.</p>

      <p>Thank you for your time and interest.</p>

      <hr style="border: none; border-top: 1px solid #eee; margin: 24px 0;" />
      <p style="color: #888; font-size: 12px;">
        This feedback was generated by TalentPlus AI. We aim to provide honest,
        actionable feedback to every applicant.
      </p>
    </div>
    """.strip()

    return subject, html_body


def email_node(state: AgentState) -> AgentState:
    """
    Sends a rejection email for candidates with score < 50.

    This node is only reached via the graph's conditional edge when
    score < 50 (see graph.py: route_after_voice). Borderline (50–59)
    and voice-eligible (>= 60) candidates never enter this node.
    """
    logger.info("[email_node] Starting rejection email for candidate %s", state["candidate_id"])

    trace = list(state.get("trace_log", []))
    score = state.get("score", 0)
    email_address = state.get("email", "")

    if not email_address:
        trace.append({
            "step":    "Email",
            "message": "No email address found. Skipping rejection email.",
            "status":  "done",
        })
        return {**state, "email_status": "skipped", "trace_log": trace}

    trace.append({
        "step":    "Email",
        "message": f"Score {score} is below threshold. Preparing rejection email...",
        "status":  "running",
    })

    try:
        resend.api_key = settings.RESEND_API_KEY

        subject, html_body = _build_rejection_email(state)

        params = {
            "from": settings.EMAIL_FROM,
            "to":   [email_address],
            "subject": subject,
            "html":    html_body,
        }

        response = resend.Emails.send(params)
        email_id = response.get("id", "unknown")

        # Mark email_sent on the evaluation record
        try:
            from talentplus_ai.candidates.models import CandidateEvaluation
            CandidateEvaluation.objects.filter(
                id=state["evaluation_id"]
            ).update(email_sent=True)
        except Exception as db_err:
            logger.warning("[email_node] Could not update email_sent flag: %s", db_err)

        trace[-1] = {
            "step":    "Email",
            "message": f"Rejection email sent to {email_address}. ID: {email_id}",
            "status":  "done",
        }

        logger.info("[email_node] Rejection email sent to %s", email_address)
        return {**state, "email_status": "sent", "trace_log": trace}

    except Exception as e:
        error_msg = f"Rejection email send failed: {e}"
        logger.error("[email_node] %s", error_msg)
        trace[-1] = {"step": "Email", "message": error_msg, "status": "error"}
        return {**state, "email_status": "failed", "trace_log": trace}


# ---------------------------------------------------------------------------
# Next-round email (called by tasks.analyze_transcript after voice scoring)
# ---------------------------------------------------------------------------

def send_next_round_email(
    candidate_name: str,
    candidate_email: str,
    evaluation_id: str,
    role_title: str,
    voice_score: float,
    final_score: float,
) -> bool:
    """
    Sends a "congratulations, you've been selected for the next round" email
    after the voice interview analysis is complete and the candidate passed.

    Called by voice/tasks.py → analyze_transcript() when
    final_merged_score >= settings.VOICE_PASS_THRESHOLD.

    Returns True on success, False on failure.
    """
    logger.info(
        "[send_next_round_email] Sending next-round email to %s for role %s "
        "(voice_score=%.1f, final_score=%.1f)",
        candidate_email,
        role_title,
        voice_score,
        final_score,
    )

    subject = f"TalentPlus AI — You've been selected for the next round! 🎉"

    html_body = f"""
    <div style="font-family: Arial, sans-serif; max-width: 600px; margin: 0 auto;">
      <h2 style="color: #1a1a2e;">Congratulations, {candidate_name or 'there'}! 🎉</h2>

      <p>We're thrilled to let you know that you've successfully completed your AI-powered
      voice screening interview for the <strong>{role_title}</strong> position — and you've
      been selected to move to the next round!</p>

      <p>Your combined evaluation score was <strong>{final_score:.0f}/100</strong>, which
      places you in our top candidate pool.</p>

      <p>Our recruiting team will be in touch shortly to schedule your next interview with
      a member of the team. Please keep an eye on your inbox.</p>

      <p>Well done, and we look forward to speaking with you!</p>

      <hr style="border: none; border-top: 1px solid #eee; margin: 24px 0;" />
      <p style="color: #888; font-size: 12px;">
        This message was sent by TalentPlus AI on behalf of our recruiting team.
      </p>
    </div>
    """.strip()

    try:
        resend.api_key = settings.RESEND_API_KEY
        response = resend.Emails.send({
            "from":    settings.EMAIL_FROM,
            "to":      [candidate_email],
            "subject": subject,
            "html":    html_body,
        })
        email_id = response.get("id", "unknown")
        logger.info(
            "[send_next_round_email] Sent to %s (email_id=%s)", candidate_email, email_id
        )

        # Mark email_sent on the evaluation record
        try:
            from talentplus_ai.candidates.models import CandidateEvaluation
            CandidateEvaluation.objects.filter(id=evaluation_id).update(email_sent=True)
        except Exception as db_err:
            logger.warning(
                "[send_next_round_email] Could not update email_sent flag: %s", db_err
            )

        return True

    except Exception as exc:
        logger.error("[send_next_round_email] Failed for %s: %s", candidate_email, exc)
        return False